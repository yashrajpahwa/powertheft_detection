"""Train the edge LightGBM model and export it as a flat C header + test vectors.

Train on folds 0-2 consumers, hold out fold 3 consumers (never seen) for the C harness test.
Outputs (edge/):
  theft_model_data.h   tree arrays (feature idx, threshold/leaf value, children)
  testdata.bin         raw hourly days of the held-out consumers + Python predictions
"""
import argparse
import json
import struct
import sys
from pathlib import Path

import lightgbm as lgb
import numpy as np
from sklearn.metrics import accuracy_score, f1_score

sys.path.insert(0, str(Path(__file__).parent))
import data
import features

ROOT = Path(__file__).resolve().parents[1]
EDGE = ROOT / "edge"

ap = argparse.ArgumentParser()
ap.add_argument("--trees", type=int, default=100)
ap.add_argument("--leaves", type=int, default=7)
ap.add_argument("--test-fold", type=int, default=3)
a = ap.parse_args()

d = data.load()
ch = data.FEATURE_SETS["all"]
F, names = features.day_features(d["X"], ch)
V = features.VALID_FROM
folds = data.group_folds(d["btype"])
tr, te = folds != a.test_fold, folds == a.test_fold

clf = lgb.LGBMClassifier(n_estimators=a.trees, num_leaves=a.leaves, learning_rate=0.1,
                         subsample=0.8, subsample_freq=1, colsample_bytree=0.8,
                         class_weight="balanced", verbose=-1, random_state=0)
clf.fit(F[tr][:, V:].reshape(-1, F.shape[-1]), d["yd"][tr][:, V:].ravel())
p_py = clf.predict(F[te][:, V:].reshape(-1, F.shape[-1]))
y_te = d["yd"][te][:, V:].ravel()
print(f"python held-out: acc {accuracy_score(y_te, p_py):.4f} macroF1 {f1_score(y_te, p_py, average='macro'):.4f}")

# ---- flatten trees ----
feat, val, left, right, roots = [], [], [], [], []


def walk(node):
    i = len(feat)
    feat.append(-1); val.append(0.0); left.append(-1); right.append(-1)
    if "leaf_value" in node:
        val[i] = node["leaf_value"]
        return i
    assert node["decision_type"] == "<=", node["decision_type"]
    feat[i] = node["split_feature"]
    val[i] = node["threshold"]
    left[i] = walk(node["left_child"])
    right[i] = walk(node["right_child"])
    return i


dump = clf.booster_.dump_model()
for t in dump["tree_info"]:
    roots.append(walk(t["tree_structure"]))
n_cls = dump["num_class"]
assert len(feat) < 32767

EDGE.mkdir(exist_ok=True)
with open(EDGE / "theft_model_data.h", "w") as f:
    f.write("/* Generated by src/export_gbm.py -- LightGBM "
            f"{a.trees} rounds x {n_cls} classes, {a.leaves} leaves. Do not edit. */\n")
    f.write("#pragma once\n#include <stdint.h>\n\n")
    f.write(f"#define THEFT_N_CLASSES {n_cls}\n#define THEFT_N_TREES {len(roots)}\n")
    f.write(f"#define THEFT_N_NODES {len(feat)}\n#define THEFT_N_FEATURES {F.shape[-1]}\n\n")

    def arr(ctype, name, xs, fmt):
        f.write(f"static const {ctype} {name}[{len(xs)}] = {{\n")
        for i in range(0, len(xs), 12):
            f.write("  " + ", ".join(fmt(x) for x in xs[i:i + 12]) + ",\n")
        f.write("};\n\n")

    arr("int16_t", "theft_roots", roots, str)
    arr("int16_t", "theft_feat", feat, str)       # -1 => leaf; left child is always node+1
    assert all(l == i + 1 for i, l in enumerate(left) if l >= 0)  # pre-order: left child = i+1
    arr("int16_t", "theft_right", right, str)
    arr("float", "theft_val", val, lambda x: f"{np.float32(x)!r}f".replace("np.float32(", "").replace(")", ""))

model_bytes = len(roots) * 2 + len(feat) * (2 + 2 + 4)
print(f"exported {len(roots)} trees, {len(feat)} nodes, model data {model_bytes/1024:.1f} KB")

# ---- test vectors: raw days for held-out consumers, streamed in order ----
Xte = d["X"][te]                       # (n, 365, 24, 10)
pred_full = np.full(d["yd"][te].shape, -1, np.int32)
pred_full[:, V:] = p_py.reshape(len(Xte), -1)
F_te = F[te]
with open(EDGE / "testdata.bin", "wb") as f:
    f.write(struct.pack("<iiii", Xte.shape[0], Xte.shape[1], 24, 10))
    f.write(Xte.astype("<f4").tobytes())
    f.write(d["yd"][te].astype("<i4").tobytes())
    f.write(pred_full.astype("<i4").tobytes())
    f.write(F_te.astype("<f4").tobytes())          # reference features for parity check
json.dump({"trees": a.trees, "leaves": a.leaves, "nodes": len(feat), "kb": model_bytes / 1024,
           "feature_names": names}, open(EDGE / "model_meta.json", "w"), indent=1)
print("wrote", EDGE / "theft_model_data.h", "and testdata.bin")
